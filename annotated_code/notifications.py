"""Ненавязчивые уведомления через системный трей Qt."""  # Участвует в реализации логики текущего компонента

from __future__ import annotations  # Подключает модуль или компонент, используемый в этом файле

from PyQt6.QtCore import QObject, QTimer, QDateTime, pyqtSignal  # Подключает модуль или компонент, используемый в этом файле
from PyQt6.QtGui import QIcon  # Подключает модуль или компонент, используемый в этом файле
from PyQt6.QtWidgets import QApplication, QSystemTrayIcon  # Подключает модуль или компонент, используемый в этом файле


class NotificationManager(QObject):  # Объявляет класс и его ответственность в приложении
    """Периодически проверяет встречи и показывает системные сообщения."""  # Участвует в реализации логики текущего компонента

    notification_sent = pyqtSignal(int)  # Присваивает значение переменной или атрибуту

    def __init__(self, database, parent=None) -> None:  # Объявляет функцию или метод для отдельной операции
        super().__init__(parent)  # Вызывает метод или функцию для выполнения действия
        self.database = database  # Сохраняет состояние или компонент внутри текущего объекта
        self.settings = database.get_settings()  # Сохраняет состояние или компонент внутри текущего объекта
        self.tray = None  # Сохраняет состояние или компонент внутри текущего объекта
        self.sent_ids: set[int] = set()  # Участвует в реализации логики текущего компонента
        self.timer = QTimer(self)  # Настраивает таймер, время или системное уведомление Qt
        self.timer.setInterval(30_000)  # Настраивает расположение или внешний вид элемента интерфейса
        self.timer.timeout.connect(self.check_meetings)  # Связывает сигнал Qt с обработчиком пользовательского действия
        self._create_tray_icon()  # Вызывает метод или функцию для выполнения действия
        self.timer.start()  # Вызывает метод или функцию для выполнения действия

    def _create_tray_icon(self) -> None:  # Объявляет функцию или метод для отдельной операции
        """Создаёт значок трея, если платформа его поддерживает."""  # Участвует в реализации логики текущего компонента
        if not QSystemTrayIcon.isSystemTrayAvailable():  # Управляет выполнением алгоритма или возвращает результат
            return  # Управляет выполнением алгоритма или возвращает результат
        self.tray = QSystemTrayIcon(QIcon(), self)  # Настраивает таймер, время или системное уведомление Qt
        self.tray.setToolTip("Meet to meet")  # Настраивает расположение или внешний вид элемента интерфейса
        self.tray.show()  # Вызывает метод или функцию для выполнения действия

    def update_settings(self, settings: dict[str, str]) -> None:  # Объявляет функцию или метод для отдельной операции
        self.settings = settings  # Сохраняет состояние или компонент внутри текущего объекта

    def check_meetings(self) -> None:  # Объявляет функцию или метод для отдельной операции
        """Проверяет, не наступило ли время напомнить о встрече."""  # Участвует в реализации логики текущего компонента
        if self.settings.get("notifications_enabled", "1") != "1":  # Управляет выполнением алгоритма или возвращает результат
            return  # Управляет выполнением алгоритма или возвращает результат
        now = QDateTime.currentDateTime()  # Настраивает таймер, время или системное уведомление Qt
        lead = max(0, int(self.settings.get("reminder_minutes", "10")))  # Присваивает значение переменной или атрибуту
        target = now.addSecs(lead * 60)  # Присваивает значение переменной или атрибуту
        now_text = now.toString("yyyy-MM-dd HH:mm")  # Присваивает значение переменной или атрибуту
        target_text = target.toString("yyyy-MM-dd HH:mm")  # Присваивает значение переменной или атрибуту
        for meeting in self.database.get_upcoming_meetings(target_text):  # Управляет выполнением алгоритма или возвращает результат
            meeting_id = int(meeting["id"])  # Присваивает значение переменной или атрибуту
            meeting_time = QDateTime.fromString(  # Настраивает таймер, время или системное уведомление Qt
                f"{meeting['meeting_date']} {meeting['start_time']}",  # Продолжает выражение, список аргументов или структуру данных
                "yyyy-MM-dd HH:mm",  # Продолжает выражение, список аргументов или структуру данных
            )  # Продолжает структуру списка, словаря или вызова функции
            if meeting_id in self.sent_ids or not meeting_time.isValid():  # Управляет выполнением алгоритма или возвращает результат
                continue  # Управляет выполнением алгоритма или возвращает результат
            if meeting_time < now or meeting_time > target:  # Управляет выполнением алгоритма или возвращает результат
                continue  # Управляет выполнением алгоритма или возвращает результат
            self.show_notification(meeting)  # Вызывает метод или функцию для выполнения действия
            self.sent_ids.add(meeting_id)  # Изменяет коллекцию, состояние или передаёт событие
            self.notification_sent.emit(meeting_id)  # Изменяет коллекцию, состояние или передаёт событие

    def show_notification(self, meeting: dict) -> None:  # Объявляет функцию или метод для отдельной операции
        """Показывает сообщение; без трея приложение просто пропускает его."""  # Участвует в реализации логики текущего компонента
        if self.tray is None:  # Управляет выполнением алгоритма или возвращает результат
            return  # Управляет выполнением алгоритма или возвращает результат
        place = meeting.get("place") or "Место не указано"  # Присваивает значение переменной или атрибуту
        self.tray.showMessage(  # Выполняет файловую операцию, обращение к БД или вывод сообщения
            "Скоро встреча",  # Продолжает выражение, список аргументов или структуру данных
            f"{meeting['title']} — {meeting['start_time']}\n{place}",  # Продолжает выражение, список аргументов или структуру данных
            QSystemTrayIcon.MessageIcon.Information,  # Настраивает таймер, время или системное уведомление Qt
            10_000,  # Продолжает выражение, список аргументов или структуру данных
        )  # Продолжает структуру списка, словаря или вызова функции
