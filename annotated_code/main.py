    def _fill_values(self) -> None:  # Объявляет функцию или метод для отдельной операции
        if not self.meeting:  # Управляет выполнением алгоритма или возвращает результат
            return  # Управляет выполнением алгоритма или возвращает результат
        self.title_edit.setText(self.meeting.get("title", ""))  # Настраивает расположение или внешний вид элемента интерфейса
        date_value = QDate.fromString(  # Создаёт или настраивает элемент интерфейса Qt
            self.meeting.get("meeting_date", ""), "yyyy-MM-dd"  # Вызывает метод или функцию для выполнения действия
        )  # Продолжает структуру списка, словаря или вызова функции
        if date_value.isValid():  # Управляет выполнением алгоритма или возвращает результат
            self.date_edit.setDate(date_value)  # Настраивает расположение или внешний вид элемента интерфейса
        start_value = QTime.fromString(  # Создаёт или настраивает элемент интерфейса Qt
            self.meeting.get("start_time", ""), "HH:mm"  # Вызывает метод или функцию для выполнения действия
        )  # Продолжает структуру списка, словаря или вызова функции
        end_value = QTime.fromString(self.meeting.get("end_time", ""), "HH:mm")  # Создаёт или настраивает элемент интерфейса Qt
        if start_value.isValid():  # Управляет выполнением алгоритма или возвращает результат
            self.start_edit.setTime(start_value)  # Настраивает расположение или внешний вид элемента интерфейса
        if end_value.isValid():  # Управляет выполнением алгоритма или возвращает результат
            self.end_edit.setTime(end_value)  # Настраивает расположение или внешний вид элемента интерфейса
        self.place_edit.setText(self.meeting.get("place", ""))  # Настраивает расположение или внешний вид элемента интерфейса
        self.description_edit.setText(self.meeting.get("description", ""))  # Настраивает расположение или внешний вид элемента интерфейса
        self.notes_edit.setPlainText(self.meeting.get("notes", ""))  # Настраивает расположение или внешний вид элемента интерфейса

    def get_data(self) -> dict[str, str]:  # Объявляет функцию или метод для отдельной операции
        """Возвращает данные формы в формате базы данных."""  # Участвует в реализации логики текущего компонента
        return {  # Управляет выполнением алгоритма или возвращает результат
            "title": self.title_edit.text().strip(),  # Продолжает выражение, список аргументов или структуру данных
            "meeting_date": self.date_edit.date().toString("yyyy-MM-dd"),  # Продолжает выражение, список аргументов или структуру данных
            "start_time": self.start_edit.time().toString("HH:mm"),  # Продолжает выражение, список аргументов или структуру данных
            "end_time": self.end_edit.time().toString("HH:mm"),  # Продолжает выражение, список аргументов или структуру данных
            "place": self.place_edit.text().strip(),  # Продолжает выражение, список аргументов или структуру данных
            "description": self.description_edit.text().strip(),  # Продолжает выражение, список аргументов или структуру данных
            "notes": self.notes_edit.toPlainText().strip(),  # Продолжает выражение, список аргументов или структуру данных
        }  # Продолжает структуру списка, словаря или вызова функции

    def accept(self) -> None:  # Объявляет функцию или метод для отдельной операции
        """Проверяет поля перед закрытием окна."""  # Участвует в реализации логики текущего компонента
        if not self.title_edit.text().strip():  # Управляет выполнением алгоритма или возвращает результат
            QMessageBox.warning(self, "Проверка данных", "Введите название встречи.")  # Выполняет файловую операцию, обращение к БД или вывод сообщения
            self.title_edit.setFocus()  # Настраивает расположение или внешний вид элемента интерфейса
            return  # Управляет выполнением алгоритма или возвращает результат
        if self.start_edit.time() >= self.end_edit.time():  # Управляет выполнением алгоритма или возвращает результат
            QMessageBox.warning(  # Выполняет файловую операцию, обращение к БД или вывод сообщения
                self,  # Продолжает выражение, список аргументов или структуру данных
                "Проверка времени",  # Продолжает выражение, список аргументов или структуру данных
                "Время окончания должно быть позже времени начала.",  # Продолжает выражение, список аргументов или структуру данных
            )  # Продолжает структуру списка, словаря или вызова функции
            return  # Управляет выполнением алгоритма или возвращает результат
        super().accept()  # Вызывает метод или функцию для выполнения действия


