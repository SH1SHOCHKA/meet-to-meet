        self.place_edit = QLineEdit()  # Создаёт или настраивает элемент интерфейса Qt
        self.place_edit.setPlaceholderText("Zoom, Google Meet, офис или ссылка")  # Настраивает расположение или внешний вид элемента интерфейса
