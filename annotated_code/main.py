    def _validate_shortcuts(self, settings: dict[str, str]) -> bool:  # Объявляет функцию или метод для отдельной операции
        """Проверяет, что сочетания корректны и не повторяются."""  # Участвует в реализации логики текущего компонента
        used: dict[str, str] = {}  # Участвует в реализации логики текущего компонента
        for key, value in settings.items():  # Управляет выполнением алгоритма или возвращает результат
            if not key.startswith("shortcut_") or not value:  # Управляет выполнением алгоритма или возвращает результат
                continue  # Управляет выполнением алгоритма или возвращает результат
            sequence = QKeySequence(value)  # Создаёт или настраивает элемент интерфейса Qt
            if sequence.isEmpty():  # Управляет выполнением алгоритма или возвращает результат
                QMessageBox.warning(self, "Горячие клавиши", f"Некорректное сочетание: {value}")  # Выполняет файловую операцию, обращение к БД или вывод сообщения
                return True  # Управляет выполнением алгоритма или возвращает результат
            normalized = sequence.toString()  # Присваивает значение переменной или атрибуту
            if normalized in used:  # Управляет выполнением алгоритма или возвращает результат
                QMessageBox.warning(  # Выполняет файловую операцию, обращение к БД или вывод сообщения
                    self,  # Продолжает выражение, список аргументов или структуру данных
                    "Горячие клавиши",  # Продолжает выражение, список аргументов или структуру данных
                    f"Сочетание {normalized} используется дважды.",  # Продолжает выражение, список аргументов или структуру данных
                )  # Продолжает структуру списка, словаря или вызова функции
                return True  # Управляет выполнением алгоритма или возвращает результат
            used[normalized] = key  # Участвует в реализации логики текущего компонента
        return False  # Управляет выполнением алгоритма или возвращает результат


